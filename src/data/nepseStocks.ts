/**
 * Deterministic pseudo-random number generator for realistic historical market data
 */
function seededRandom(seed: number) {
  const x = Math.sin(seed++) * 10000;
  return x - Math.floor(x);
}

/**
 * Generates continuous daily OHLCV candles spanning from 2016 to current date
 * (Nepal trading calendar: Sunday to Thursday, ~2,650 sessions)
 */
export function generateCandles(basePrice: number, volatility: number, trend: number, seedBase: number): Candle[] {
  const candles: Candle[] = [];
  // Nepal market history starts Jan 2016
  const startDate = new Date(2016, 0, 3); // 2016-01-03 (Sunday)
  const endDate = new Date(2026, 9, 7); // 2026-10-07
  let currentPrice = Math.max(10, basePrice * 0.55); // base price back in 2016

  let currentDate = new Date(startDate);
  let s = seedBase;

  while (currentDate <= endDate) {
    const dayOfWeek = currentDate.getDay();
    // 0 is Sunday, 4 is Thursday (Nepal trading days)
    if (dayOfWeek >= 0 && dayOfWeek <= 4) {
      const r1 = seededRandom(s++);
      const r2 = seededRandom(s++);
      const r3 = seededRandom(s++);
      const r4 = seededRandom(s++);

      const year = currentDate.getFullYear();
      // Realistic macro market regime drifts for Nepal:
      // 2016-mid 2016: Bull run to 1881
      // 2017-2019: Bear cycle / consolidation (down to 1100)
      // 2020-2021: Post-COVID historic expansion (up to 3200)
      // 2022-2023: Liquidity crunch / high interest rates
      // 2024-2026: Monetary easing recovery
      let regimeDrift = 0;
      if (year === 2016) regimeDrift = 0.0012;
      else if (year >= 2017 && year <= 2019) regimeDrift = -0.0006;
      else if (year >= 2020 && year <= 2021) regimeDrift = 0.0018;
      else if (year === 2022) regimeDrift = -0.0012;
      else regimeDrift = 0.0004;

      const dailyDeltaPct = (r1 - 0.492 + trend * 0.02 + regimeDrift) * volatility;
      const open = Number(currentPrice.toFixed(2));
      const close = Number(Math.max(10, open * (1 + dailyDeltaPct)).toFixed(2));
      const high = Number((Math.max(open, close) * (1 + r2 * volatility * 0.55)).toFixed(2));
      const low = Number((Math.min(open, close) * (1 - r3 * volatility * 0.55)).toFixed(2));
      const baseVol = Math.floor(basePrice > 1000 ? 5000 : basePrice > 500 ? 25000 : 75000);
      const volume = Math.floor(baseVol * (0.5 + r4 * 1.5));

      const month = String(currentDate.getMonth() + 1).padStart(2, '0');
      const day = String(currentDate.getDate()).padStart(2, '0');
      const timeStr = `${year}-${month}-${day}`;

      candles.push({
        time: timeStr,
        open,
        high,
        low,
        close,
        volume,
      });

      currentPrice = close;
    }
    currentDate.setDate(currentDate.getDate() + 1);
  }

  // Ensure last candle matches basePrice closely for consistency
  if (candles.length > 0) {
    const last = candles[candles.length - 1];
    last.close = basePrice;
    last.high = Math.max(last.high, basePrice);
    last.low = Math.min(last.low, basePrice);
  }

  return candles;
}

